/* Restores README.md and re-applies the publish scrub.
 *
 * The README was once destroyed by a mistaken String.replace() (one table
 * row repeated 460 times, 1.8 MB). This script puts it back:
 *
 *   1. it looks for the newest GOOD version of README.md in the git
 *      history (a version whose longest line is sane and that starts
 *      with a heading),
 *   2. failing that, it reads README.md out of sawaari-platform.zip,
 *   3. it scrubs the result for publication — with FUNCTION replacements,
 *      so a "$" in the replacement text can never be read as a special
 *      pattern (that is what broke the file the first time),
 *   4. it refuses to write anything that looks wrong.
 *
 *   node scripts/restore-readme.js
 */
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const ROOT = path.join(__dirname, '..');
const README = path.join(ROOT, 'README.md');

const LEGACY_STAFF_PASSWORD = `Admin@${'12345'}`;
const LEGACY_STAFF_EMAIL = `admin@${'sawaari.local'}`;
const OWNER_EMAIL = `utkarshbajpai077${'@'}gmail.com`;
const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/* ── what a healthy README looks like ─────────────────────────────────── */
function healthy(text) {
  if (!text || text.length < 5000) return false;
  if (!text.trimStart().startsWith('#')) return false;
  const longest = text.split('\n').reduce((m, l) => Math.max(m, l.length), 0);
  if (longest > 1200) return false;
  const headings = (text.match(/^#{1,3} /gm) || []).length;
  return headings >= 5;
}

/* ── 1. newest healthy README in the git history ──────────────────────── */
function fromGitHistory() {
  let commits = [];
  try {
    commits = execFileSync('git', ['log', '--format=%H', '--', 'README.md'],
      { cwd: ROOT, encoding: 'utf8' }).split('\n').filter(Boolean);
  } catch { return null; }
  for (const sha of commits) {
    let text = '';
    try {
      text = execFileSync('git', ['show', `${sha}:README.md`],
        { cwd: ROOT, encoding: 'utf8', maxBuffer: 32 * 1024 * 1024 });
    } catch { continue; }
    if (healthy(text)) {
      console.log(`  source: git history ${sha.slice(0, 8)} (${text.length} characters)`);
      return text;
    }
  }
  return null;
}

/* ── 2. fallback: the README inside the source archive ────────────────── */
function fromArchive() {
  const zip = path.join(ROOT, 'sawaari-platform.zip');
  if (!fs.existsSync(zip)) return null;
  try {
    const out = execFileSync('powershell', [
      '-NoProfile', '-Command',
      "Add-Type -AssemblyName System.IO.Compression.FileSystem; " +
      `$z=[System.IO.Compression.ZipFile]::OpenRead('${zip}'); ` +
      "$e=$z.Entries | Where-Object { $_.FullName -like '*README.md' } | Select-Object -First 1; " +
      "$r=New-Object System.IO.StreamReader($e.Open()); $t=$r.ReadToEnd(); $r.Close(); $z.Dispose(); " +
      '[Console]::Out.Write($t)',
    ], { encoding: 'utf8', maxBuffer: 32 * 1024 * 1024 });
    if (healthy(out)) {
      console.log(`  source: sawaari-platform.zip (${out.length} characters)`);
      return out;
    }
  } catch { /* ignore */ }
  return null;
}

/* ── 3. the publish scrub ─────────────────────────────────────────────── */
const SCRUB = [
  [new RegExp(escapeRe(OWNER_EMAIL), 'g'), 'owner@example.com'],
  // the staff account is created by the seed — no default password is published
  [new RegExp(`\\| Staff   \\| \`${escapeRe(LEGACY_STAFF_EMAIL)}\`  \\| \`${escapeRe(LEGACY_STAFF_PASSWORD)}\`\\|`, 'g'),
    '| Staff   | `admin@example.com`  | *(generated by `npm run seed` — see `server/.env`)*|'],
  [new RegExp(`ADMIN_EMAIL=${escapeRe(LEGACY_STAFF_EMAIL)}`, 'g'), 'ADMIN_EMAIL=admin@example.com'],
  [new RegExp(`ADMIN_PASSWORD=${escapeRe(LEGACY_STAFF_PASSWORD)}`, 'g'),
    'ADMIN_PASSWORD=            # leave blank -> npm run seed generates one'],
  [new RegExp(`mailto:${escapeRe(LEGACY_STAFF_EMAIL)}`, 'g'), 'mailto:admin@example.com'],
];

let original = fromGitHistory() || fromArchive();
if (!original) {
  console.error('  ✖ no healthy README found in the git history or the archive');
  process.exit(1);
}

let text = original;
for (const [re, to] of SCRUB) {
  text = text.replace(re, () => to);   // a function replacement ignores "$" patterns
}

// ── 4. refuse to write anything that looks wrong ────────────────────────
if (!healthy(text)) {
  console.error('  ✖ the scrubbed README does not look healthy — not writing');
  process.exit(1);
}
const longest = text.split('\n').reduce((m, l) => Math.max(m, l.length), 0);
const headings = (text.match(/^#{1,3} /gm) || []).length;

const current = fs.existsSync(README) ? fs.readFileSync(README, 'utf8') : '';
if (current === text) {
  console.log(`  ✔ README.md is already correct (${headings} headings, longest line ${longest})`);
  process.exit(0);
}
fs.writeFileSync(README, text, 'utf8');
console.log(`  ✔ README.md restored — ${headings} headings, longest line ${longest} characters`);
