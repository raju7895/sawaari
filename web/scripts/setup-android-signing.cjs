/* Creates the release signing keystore and wires it into Gradle.
 *
 * The keystore and its passwords are generated locally and stored in
 * android/keystore.properties, which is git-ignored — no secret is ever
 * committed. Losing that file means a new app identity, so the file is
 * also copied into server/backups/ (also git-ignored).
 *
 *   node scripts/setup-android-signing.js
 */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { spawnSync } = require('child_process');

const ROOT = path.join(__dirname, '..', '..');   // project root (web/ is one level down)
const ANDROID = path.join(ROOT, 'web', 'android');
const TC = path.join(ROOT, '.toolchain');
const JAVA_HOME = process.env.JAVA_HOME || path.join(TC, 'jdk');
const KEYTOOL = path.join(JAVA_HOME, 'bin', 'keytool.exe');
const PROPS = path.join(ANDROID, 'keystore.properties');
const KEYSTORE = path.join(ANDROID, 'sawaari-release.keystore');

const randomPassword = (len = 24) => {
  const alphabet = 'ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789';
  const bytes = crypto.randomBytes(len * 2);
  let out = '';
  for (let i = 0; i < len; i++) out += alphabet[bytes[i] % alphabet.length];
  return out;
};

function main() {
  if (!fs.existsSync(KEYTOOL)) {
    console.error(`keytool not found at ${KEYTOOL}`);
    console.error('Run: node scripts/setup-android-toolchain.js');
    process.exit(1);
  }

  if (fs.existsSync(KEYSTORE) && fs.existsSync(PROPS)) {
    console.log('✔ keystore already exists — keeping it (delete both files to rotate)');
    wireGradle();
    return;
  }

  const storePass = randomPassword(24);
  const keyPass = storePass;      // PKCS12 keystores use one password for both
  const alias = 'sawaari';

  console.log('Creating the release keystore (valid 30 years)…');
  const r = spawnSync(KEYTOOL, [
    '-genkeypair',
    '-v',
    '-keystore', KEYSTORE,
    '-storepass', storePass,
    '-keypass', keyPass,
    '-alias', alias,
    '-keyalg', 'RSA',
    '-keysize', '2048',
    '-validity', '10950',           // 30 years
    '-dname', 'CN=Sawaari, OU=Mobile, O=Sawaari, L=Ahmedabad, S=Gujarat, C=IN',
  ], { stdio: 'inherit' });
  if (r.status !== 0) {
    console.error('keytool failed');
    process.exit(1);
  }

  fs.writeFileSync(PROPS, [
    '# Generated by scripts/setup-android-signing.js — git-ignored.',
    '# Back this file up: without it you cannot publish updates to the same app.',
    `storeFile=${path.basename(KEYSTORE)}`,
    `storePassword=${storePass}`,
    `keyAlias=${alias}`,
    `keyPassword=${keyPass}`,
    '',
  ].join('\n'));

  // keep a copy with the backups (also git-ignored)
  const backupDir = path.join(ROOT, 'server', 'backups');
  fs.mkdirSync(backupDir, { recursive: true });
  fs.copyFileSync(PROPS, path.join(backupDir, 'android-keystore.properties'));
  fs.copyFileSync(KEYSTORE, path.join(backupDir, path.basename(KEYSTORE)));

  console.log('✔ keystore created');
  console.log(`  ${KEYSTORE}`);
  console.log(`  ${PROPS}`);
  console.log('  (a copy is kept in server/backups/ — git-ignored)');
  wireGradle();
}

function wireGradle() {
  const gradlePath = path.join(ANDROID, 'app', 'build.gradle');
  let g = fs.readFileSync(gradlePath, 'utf8');
  if (g.includes('sawaariRelease')) {
    console.log('✔ Gradle already wired for signing');
    return;
  }
  g = g.replace(
    'apply plugin: \'com.android.application\'',
    `apply plugin: 'com.android.application'

// Release signing — credentials come from android/keystore.properties
// (generated locally, git-ignored). Never commit them.
def keystorePropsFile = rootProject.file("keystore.properties")
def keystoreProps = new Properties()
if (keystorePropsFile.exists()) {
    keystoreProps.load(new FileInputStream(keystorePropsFile))
}`
  );
  g = g.replace(
    `    buildTypes {
        release {
            minifyEnabled false
            proguardFiles getDefaultProguardFile('proguard-android.txt'), 'proguard-rules.pro'
        }
    }`,
    `    signingConfigs {
        sawaariRelease {
            if (keystoreProps['storeFile']) {
                storeFile file(keystoreProps['storeFile'])
                storePassword keystoreProps['storePassword']
                keyAlias keystoreProps['keyAlias']
                keyPassword keystoreProps['keyPassword']
            }
        }
    }
    buildTypes {
        release {
            if (keystoreProps['storeFile']) {
                signingConfig signingConfigs.sawaariRelease
            }
            minifyEnabled false
            proguardFiles getDefaultProguardFile('proguard-android.txt'), 'proguard-rules.pro'
        }
    }`
  );
  fs.writeFileSync(gradlePath, g);
  console.log('✔ Gradle wired for release signing');
}

main();
